/**
 * SkillBox consumer i18n.
 * English / Hindi / Marathi are first-class; more languages slot into `LANGS`.
 */
export type Lang = "en" | "hi" | "mr";

export interface LangMeta {
  code: Lang;
  name: string;
  native: string;
  voice: boolean; // local voice pack available
}

export const LANGS: LangMeta[] = [
  { code: "en", name: "English", native: "English", voice: true },
  { code: "hi", name: "Hindi", native: "हिन्दी", voice: true },
  { code: "mr", name: "Marathi", native: "मराठी", voice: true },
];

export const langMeta = (code: Lang): LangMeta =>
  LANGS.find((l) => l.code === code) ?? LANGS[0];

